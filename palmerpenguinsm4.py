import math

#constants
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

#list of species names
species_names = [
    SP_CHINSTRAP,
    SP_GENTOO,
    SP_ADELIE
]

#list of species counts
species_counts = [
    NUM_CHINSTRAP,
    NUM_GENTOO,
    NUM_ADELIE
]

#calculate dataset stats
total_species = len(species_names)
total_penguins = sum(species_counts)
average_penguins = total_penguins / total_species
average_penguins_rounded_up = math.ceil(average_penguins)

chinstrap_percent = species_counts[0] / total_penguins * 100
gentoo_percent = species_counts[1] / total_penguins * 100
adelie_percent = species_counts[2] / total_penguins * 100

#List of species percentages
species_percentages = [
    chinstrap_percent,
    gentoo_percent,
    adelie_percent
]

largest_count = max(species_counts)
smallest_count = min(species_counts)

largest_index = species_counts.index(largest_count)
smallest_index = species_counts.index(smallest_count)

largest_species = species_names[largest_index]
smallest_species = species_names[smallest_index]


#Output the species names with introductory text
print("Introducing the Palmer Penguins:")
print("\t" + SP_CHINSTRAP + "!")
print("\t" + SP_GENTOO + "!")
print("and last but not least...")
print("\t" + SP_ADELIE + "!" )
print()

print(f"There are a total of {total_species} penguin species in this dataset.")
print(f"There are a total of {total_penguins} penguins in this dataset.")
print(f"The average number of penguins per species is {average_penguins}.")
print(f"The average rounded up is {average_penguins_rounded_up} penguins.")

print()

print(f"{SP_CHINSTRAP}: {species_counts[0]} ({chinstrap_percent}%)")
print(f"{SP_GENTOO}: {species_counts[1]} ({gentoo_percent}%)")
print(f"{SP_ADELIE}: {species_counts[2]} ({adelie_percent}%)")

print()

print(f"The species with the largest population is {largest_species} with {largest_count} penguins.")
print(f"The species with the smallest population is {smallest_species} with {smallest_count} penguins.")

#Allow user to select a species
print()
print("Explore a species:")

#Ask user to enter a species
species_choice = input("Enter Chinstrap, Gentoo, or Adelie: ")

#Check if selected species is valid
if species_choice not in species_names:
  print(f"{species_choice} is not one of the species in this dataset.")
else:
  if species_choice == species_names[0]:
    selected_index = 0
  elif species_choice == species_names[1]:
    selected_index = 1
  else:
    selected_index = 2

#Retrieve selected species data
selected_species = species_names[selected_index]
selected_count = species_counts[selected_index]
selected_percent = species_percentages[selected_index]

print(f"Species: {selected_species}")
print(f"Count: {selected_count}")
print(f"Percentage: {selected_percent:.2f}%")

#Classify species by percentage
if selected_percent < 25:
  size_category = "small"
elif (selected_percent >= 25) and (selected_percent < 40):
  size_category = "medium"
else:
  size_category = "large"

print(f"Size category: {size_category}")

#Determine the species' relative position
if (selected_species == largest_species) or (selected_species == smallest_species):

    #Check for largest
    if selected_species == largest_species:
        position_description = "largest"
    else:
        position_description = "smallest"

else:
  position_description = "middle-sized"

print(f"Relative position: {position_description}")

#Compare selected count to the average
average_position = "above" if selected_count > average_penguins else "below"

print(f"Compared to average: {average_position}")